def nom(anglais, pris):
    mots = re.findall(r"[a-z0-9]+", anglais.lower().replace("½", "half"))[:5] or ["texte"]
    base = "_".join(mots)[:40]
    cle, n = base, 2
    while cle in pris:
        cle = base + "_" + str(n)
        n += 1
    pris.add(cle)
    return cle


def java(texte):
    return texte.replace("\\", "\\\\").replace('"', '\\"')


